import { mount } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import Input from './Input.vue'

describe('terminal input', () => {
  beforeEach(() => { vi.spyOn(window, 'scrollTo').mockImplementation(() => {}) })
  afterEach(() => { vi.restoreAllMocks() })

  it('emits an uppercase command and resets the field', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue('/help')
    await field.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('sendCommand')).toEqual([[{ question: '/HELP', answer: '' }]])
    expect(field.element.value).toBe('')
    wrapper.unmount()
  })

  it('disguises a secret, confirms it, and sends it with the question', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue(' ')
    for (const character of 'DIEGO') await field.setValue(field.element.value + character)
    expect(field.element.value).not.toContain('DIEGO')
    await field.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('sendCommand')).toBeUndefined()
    await field.setValue(field.element.value + ' QUEM SOU EU?')
    await field.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('sendCommand')?.[0]?.[0]).toMatchObject({ answer: 'DIEGO' })
    wrapper.unmount()
  })

  it('removes deleted characters from the secret', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue(' ')
    for (const character of 'AB') await field.setValue(field.element.value + character)
    await field.setValue(field.element.value.slice(0, -1))
    await field.trigger('keydown', { key: 'Enter' })
    await field.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('sendCommand')?.[0]?.[0]).toMatchObject({ answer: 'A' })
    wrapper.unmount()
  })

  it('cancels the secret with Escape', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue(' ')
    await field.setValue(field.element.value + 'SEGREDO')
    await field.trigger('keydown', { key: 'Escape' })
    await field.setValue('oi')
    await field.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('sendCommand')).toEqual([[{ question: 'OI', answer: '' }]])
    wrapper.unmount()
  })

  it('prevents ordinary keystrokes while writing, without changing the textarea contract', async () => {
    const wrapper = mount(Input, { props: { enable: false } })
    const field = wrapper.get('textarea')
    expect(field.attributes('readonly')).toBeUndefined()
    await wrapper.setProps({ write: 'CALCULANDO...' })
    expect(field.element.value).toBe('CALCULANDO...')
    const event = new KeyboardEvent('keydown', { key: 'A', bubbles: true, cancelable: true })
    field.element.dispatchEvent(event)
    expect(event.defaultPrevented).toBe(true)
    expect(wrapper.emitted('sendCommand')).toBeUndefined()
    wrapper.unmount()
  })

  it('restores focus on blur and when the window regains focus', async () => {
    const wrapper = mount(Input, { attachTo: document.body })
    const field = wrapper.get('textarea')
    expect(document.activeElement).toBe(field.element)
    field.element.blur()
    expect(document.activeElement).toBe(field.element)
    const focus = vi.spyOn(field.element, 'focus')
    window.dispatchEvent(new Event('focus'))
    expect(focus).toHaveBeenCalled()
    wrapper.unmount()
    focus.mockClear()
    window.dispatchEvent(new Event('focus'))
    expect(focus).not.toHaveBeenCalled()
  })

  it('does not rewind the disguise when a secret character is deleted', async () => {
    vi.spyOn(Math, 'random').mockReturnValue(.5)
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue(' ')
    for (const character of 'AB') await field.setValue(field.element.value + character)
    expect(field.element.value.toUpperCase()).toBe('QUE')
    await field.setValue(field.element.value.slice(0, -1))
    await field.setValue(field.element.value + 'C')
    expect(field.element.value.toUpperCase()).toBe('QUR')
    await field.trigger('keydown', { key: 'Enter' })
    await field.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('sendCommand')?.[0]?.[0]).toMatchObject({ answer: 'AC' })
    wrapper.unmount()
  })

  it('does not discard edits inside the disguise or force append-only selection', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue(' ')
    for (const character of 'ABC') await field.setValue(field.element.value + character)
    field.element.value = 'X' + field.element.value
    field.element.setSelectionRange(1, 1)
    const selection = vi.spyOn(field.element, 'setSelectionRange')
    await field.trigger('input')
    expect(field.element.value.startsWith('X')).toBe(true)
    expect(selection).not.toHaveBeenCalled()
    wrapper.unmount()
  })

  it('measures the cursor and field height and mirrors text up to the native selection', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    const mirrorCaret = wrapper.get('span')
    Object.defineProperties(mirrorCaret.element, {
      offsetLeft: { value: 24 },
      offsetTop: { value: 40 },
    })
    Object.defineProperty(field.element, 'scrollHeight', { value: 80 })
    await field.setValue('teste')
    field.element.setSelectionRange(2, 2)
    await field.trigger('click')
    expect(mirrorCaret.element.parentElement?.textContent).toBe('TE')
    expect(field.element.style.height).toBe('80px')
    const cursor = wrapper.get('div[style*="left:"]')
    expect(cursor.attributes('style')).toContain('left: 24px')
    expect(cursor.attributes('style')).toContain('top: 40px')
    expect(window.scrollTo).toHaveBeenCalledWith(0, document.body.scrollHeight)
    wrapper.unmount()
  })

  it('recalls submitted questions and restores the unfinished draft with the caret at the end', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    for (const text of ['PRIMEIRA', 'SEGUNDA']) {
      await field.setValue(text)
      await field.trigger('keydown', { key: 'Enter' })
    }
    await field.setValue('RASCUNHO')
    await field.trigger('keydown', { key: 'ArrowUp' })
    expect(field.element.value).toBe('SEGUNDA')
    expect(field.element.selectionStart).toBe('SEGUNDA'.length)
    await field.trigger('keydown', { key: 'ArrowUp' })
    expect(field.element.value).toBe('PRIMEIRA')
    await field.trigger('keydown', { key: 'ArrowDown' })
    expect(field.element.value).toBe('SEGUNDA')
    await field.trigger('keydown', { key: 'ArrowDown' })
    expect(field.element.value).toBe('RASCUNHO')
    wrapper.unmount()
  })

  it('stores only the visible question and never reuses an associated secret', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue(' ')
    for (const c of 'SEGREDO') await field.setValue(field.element.value + c)
    await field.trigger('keydown', { key: 'Enter' })
    await field.setValue(field.element.value + ' QUEM SOU EU?')
    const visible = field.element.value.toUpperCase()
    await field.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('sendCommand')?.[0]?.[0]).toMatchObject({ answer: 'SEGREDO' })
    await field.trigger('keydown', { key: 'ArrowUp' })
    expect(field.element.value).toBe(visible)
    expect(field.element.value).not.toContain('SEGREDO')
    await field.trigger('keydown', { key: 'Enter' })
    expect(wrapper.emitted('sendCommand')?.[1]?.[0]).toEqual({ question: visible, answer: '' })
    wrapper.unmount()
  })

  it('does not navigate while entering a secret or after confirming it', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue('/HELP')
    await field.trigger('keydown', { key: 'Enter' })
    await field.setValue(' ')
    for (const c of 'NEO') await field.setValue(field.element.value + c)
    const disguise = field.element.value
    await field.trigger('keydown', { key: 'ArrowUp' })
    expect(field.element.value).toBe(disguise)
    await field.trigger('keydown', { key: 'Enter' })
    await field.trigger('keydown', { key: 'ArrowUp' })
    expect(field.element.value).toBe(disguise)
    await field.trigger('keydown', { key: 'Escape' })
    await field.trigger('keydown', { key: 'ArrowUp' })
    expect(field.element.value).toBe('/HELP')
    wrapper.unmount()
  })

  it('does not recall history during output, composition or modified arrow keys', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue('/HELP')
    await field.trigger('keydown', { key: 'Enter' })
    await field.setValue('DRAFT')
    for (const modifiers of [{ ctrlKey: true }, { altKey: true }, { shiftKey: true }, { metaKey: true }, { isComposing: true }]) {
      await field.trigger('keydown', { key: 'ArrowUp', ...modifiers })
      expect(field.element.value).toBe('DRAFT')
    }
    await wrapper.setProps({ enable: false, write: 'CALCULANDO...' })
    await field.trigger('keydown', { key: 'ArrowUp' })
    expect(field.element.value).toBe('CALCULANDO...')
    wrapper.unmount()
  })

  it('treats edited recalls as new drafts and Escape cancels navigation', async () => {
    const wrapper = mount(Input)
    const field = wrapper.get('textarea')
    await field.setValue('ENVIADO')
    await field.trigger('keydown', { key: 'Enter' })
    await field.trigger('keydown', { key: 'ArrowUp' })
    await field.setValue('EDITADO')
    await field.trigger('keydown', { key: 'ArrowUp' })
    expect(field.element.value).toBe('ENVIADO')
    await field.trigger('keydown', { key: 'ArrowDown' })
    expect(field.element.value).toBe('EDITADO')
    await field.trigger('keydown', { key: 'ArrowUp' })
    await field.trigger('keydown', { key: 'Escape' })
    await field.trigger('keydown', { key: 'ArrowDown' })
    expect(field.element.value).toBe('')
    wrapper.unmount()
  })
})
